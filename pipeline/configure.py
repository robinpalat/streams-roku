#!/usr/bin/env python3
"""Generate the Roku metadata config for development or GitHub Pages.

Development keeps the optional LAN server. Production points at the public
GitHub Pages URL derived from the repository remote; the repository is never
hardcoded.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

from .pages import PagesConfigError, normalize_meta_path, pages_base, resolve_repo_slug, site_base

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "pipeline" / "config" / "roku.json"
GENERATED = ROOT / "pipeline" / "config" / "roku.generated.json"
APP_CONFIG = ROOT / "source" / "app_config.brs"
SERVICE = ROOT / "pipeline" / "server" / "roku-epg.service.generated"


def detect_host() -> str:
    try:
        out = subprocess.check_output(
            ["ip", "-4", "route", "get", "192.168.1.1"],
            text=True, stderr=subprocess.DEVNULL,
        )
        match = re.search(r"\bsrc\s+(\d+\.\d+\.\d+\.\d+)", out)
        if match:
            return match.group(1)
    except Exception:
        pass
    try:
        out = subprocess.check_output(["ip", "-4", "-o", "addr", "show", "scope", "global"], text=True)
        addresses = re.findall(r"inet\s+(\d+\.\d+\.\d+\.\d+)", out)
        for address in addresses:
            if address.startswith("192.168."):
                return address
        for address in addresses:
            if not address.startswith(("127.", "169.254.")):
                return address
    except Exception:
        pass
    raise RuntimeError("could not detect LAN IPv4; pass --host explicitly")


def write_service(port: int, artifacts: Path) -> None:
    log_dir = Path.home() / ".local" / "state" / "streams-roku"
    log_dir.mkdir(parents=True, exist_ok=True)
    service = f"""[Unit]
Description=Streams Roku EPG local server (development)
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
WorkingDirectory={ROOT}
Environment=PYTHONUNBUFFERED=1
ExecStart=/usr/bin/python3 -u -m pipeline.serve --dir {artifacts} --port {port} --bind 0.0.0.0
Restart=on-failure
RestartSec=5
StandardOutput=append:{log_dir / 'epg-server.log'}
StandardError=append:{log_dir / 'epg-server.log'}

[Install]
WantedBy=default.target
"""
    SERVICE.parent.mkdir(parents=True, exist_ok=True)
    SERVICE.write_text(service, encoding="utf-8")


def write_app_config(base: str, source_match: str) -> None:
    APP_CONFIG.write_text(
        "' GENERATED by pipeline/configure.py; do not edit by hand.\n"
        "function DefaultMetaBase() as String\n"
        f"    return \"{base}\"\n"
        "end function\n"
        f"function DefaultMetaSourceMatch() as String\n"
        f"    return \"{source_match}\"\n"
        "end function\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", choices=["development", "production"], default="development")
    parser.add_argument("--host", default="", help="development override host; empty = auto detect")
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--match", default="")
    parser.add_argument("--repo-url", default="", help="production repository URL or owner/name")
    args = parser.parse_args()

    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    meta_path = normalize_meta_path(cfg.get("metaPath") or "/real/")
    source_match = args.match or cfg.get("sourceMatch") or "robinpalat/streams"
    artifacts_value = cfg.get("artifactsDir") or "pipeline/out"
    artifacts = (ROOT / artifacts_value).resolve()

    if args.profile == "production":
        try:
            repo = resolve_repo_slug(args.repo_url or (cfg.get("production") or {}).get("repoUrl") or "")
        except PagesConfigError as exc:
            print(f"error: {exc}")
            return 2
        base = pages_base(repo, meta_path)
        generated = {
            "profile": "production",
            "repo": repo,
            "pagesBase": site_base(repo),
            "metaPath": meta_path,
            "metaBase": base,
            "sourceMatch": source_match,
            "artifactsDir": artifacts_value,
        }
        write_app_config(base, source_match)
    else:
        if args.repo_url:
            parser.error("--repo-url is only valid with --profile production")
        host = args.host or cfg.get("host") or detect_host()
        port = args.port or int(cfg.get("port") or 8001)
        base = f"http://{host}:{port}{meta_path}"
        generated = {
            "profile": "development",
            "host": host,
            "port": port,
            "metaPath": meta_path,
            "metaBase": base,
            "sourceMatch": source_match,
            "artifactsDir": artifacts_value,
        }
        write_app_config(base, source_match)
        write_service(port, artifacts)

    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(json.dumps(generated, indent=2) + "\n", encoding="utf-8")

    print(f"profile={generated['profile']}")
    print(f"metaBase={base}")
    print(f"appConfig={APP_CONFIG}")
    if generated["profile"] == "development":
        print(f"service={SERVICE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
